# -----------------------------------------------------------
# Funções auxiliares
# -----------------------------------------------------------

def criar_pasta(path):
    os.makedirs(path, exist_ok=True)

def corr_pearson(x, y):
    """Correlação Pearson simples, ignorando NaNs."""
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    mask = ~np.isnan(x) & ~np.isnan(y)
    if mask.sum() < 2:
        return np.nan
    return np.corrcoef(x[mask], y[mask])[0, 1]

# -----------------------------------------------------------
# Função para calcular sigma realizada anualizada por modelo
# -----------------------------------------------------------
def calc_sigma_real_h(df_vols, idx_ini, H):
    """
    Calcula a volatilidade realizada anualizada no horizonte H
    usando retornos log observados (independente do modelo).
    """
    if idx_ini + H > len(df_vols):
        return np.nan

    rets = df_vols["retorno_log"].values[idx_ini : idx_ini + H]
    var = np.sum(rets**2)
    sigma_periodo = np.sqrt(var)
    sigma_anual = sigma_periodo * np.sqrt(252 / H)
    return sigma_anual


