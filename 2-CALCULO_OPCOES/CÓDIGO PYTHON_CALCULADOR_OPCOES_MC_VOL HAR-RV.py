    grupos = df_corr_base.groupby(["modelo", "horizonte", "tipo_MC"])

    registros_corr = []

    for (modelo, H_name, tipo), grp in grupos:

        corr_call = corr_pearson(grp["erro_sigma"], grp["erro_call"])
        corr_put  = corr_pearson(grp["erro_sigma"], grp["erro_put"])

        registros_corr.append({
            "modelo": modelo,
            "horizonte": H_name,
            "tipo_MC": tipo,
            "corr_erro_sigma__erro_CALL": corr_call,
            "corr_erro_sigma__erro_PUT":  corr_put,
            "n_obs": len(grp)
        })

    df_correl = pd.DataFrame(registros_corr)
    print(df_correl)

    # -----------------------------------------------------------
