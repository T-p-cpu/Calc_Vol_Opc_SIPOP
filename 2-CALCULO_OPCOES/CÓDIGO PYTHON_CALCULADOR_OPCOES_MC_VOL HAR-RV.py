    path_corr = os.path.join(outdir, "Correlacoes_sigma_erros.csv")
    df_correl.to_csv(path_corr, index=False)

    print("\n>>> Tabela de correlações salva em:", path_corr)

    # -----------------------------------------------------------
    # Gerar scatterplots erro_sigma × erro_CALL / erro_PUT
    # -----------------------------------------------------------

    print("\n>>> Gerando scatterplots erro_sigma × erro_CALL/PUT...\n")

    for (modelo, H_name, tipo), grp in grupos:

        if len(grp) < 5:
            continue  # poucos pontos, ignora

