import numpy as np
import os

# -----------------------------------------------------------
# MOTOR Monte Carlo σ DINÂMICO
# -----------------------------------------------------------

def mc_sigma_dinamica(S0, K, sigmas_h, r, q, n_sim=10000):
    """
    Simulador Monte Carlo usando σ(t) variável diariamente.

    Modelo:
    S_{t+1} = S_t * exp[(r - q - 0.5*sigma_t^2)*dt + sigma_t*sqrt(dt)*Z]

    S0        : preço inicial
    K         : strike
    sigmas_h  : vetor numpy com σ diária ao longo do horizonte
    r         : taxa livre de risco anual
    q         : yield/dividendo
    n_sim     : número de simulações Monte Carlo
    """

    H = len(sigmas_h)
    dt = 1/252

    # Matriz de choques: n_sim x H
    Z = np.random.normal(0, 1, (n_sim, H))

    # Inicialização
    ST = np.full(n_sim, S0, dtype=float)

    # Simulação passo-a-passo
    for i in range(H):
        sigma_t = sigmas_h[i]
        if sigma_t <= 0 or np.isnan(sigma_t):
            sigma_t = 1e-8

        drift = (r - q - 0.5*sigma_t**2) * dt
        shock = sigma_t * np.sqrt(dt) * Z[:, i]

        ST = ST * np.exp(drift + shock)

    # Payoffs descontados
    T = H / 252
    disc = np.exp(-r * T)

    call_price = disc * np.mean(np.maximum(ST - K, 0))
    put_price  = disc * np.mean(np.maximum(K - ST, 0))

    return call_price, put_price

