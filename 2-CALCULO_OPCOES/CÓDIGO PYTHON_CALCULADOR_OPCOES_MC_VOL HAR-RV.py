        plt.axhline(0, color='gray', linewidth=0.8)
        plt.axvline(0, color='gray', linewidth=0.8)
        plt.title(f"Erro σ × Erro CALL\n{modelo} – {H_name} – {tipo}")
        plt.xlabel("Erro de σ (sigma_modelo - sigma_real)")
        plt.ylabel("Erro CALL (MC - payoff_real)")
        plt.tight_layout()
        fname_call = f"scatter_erroSigma_erroCALL_{modelo}_{H_name}_{tipo}.png"
        plt.savefig(os.path.join(scatter_dir, fname_call), dpi=200)
        plt.close()

        # Scatter para PUT
        plt.figure(figsize=(6,4))
