def load_sheet(path, prefix, keep_price=False):
    df = pd.read_excel(path)
    df.columns = [col.lower() for col in df.columns]
    df['data'] = pd.to_datetime(df['data'])

    # VOL REAL AGORA TEM NOME ÚNICO POR MODELO
    rename_dict = {
        'volatilidade_realizada': f'vol_real_{prefix}',
        'volatilidade_'+prefix+'_diaria': f'vol_{prefix}_dia',
        'volatilidade_'+prefix+'_1w_anualizada': f'vol_{prefix}_1w',
        'volatilidade_'+prefix+'_1m_anualizada': f'vol_{prefix}_1m',
        'volatilidade_'+prefix+'_1y_anualizada': f'vol_{prefix}_1y'
    }

    df = df.rename(columns={c: rename_dict[c] for c in rename_dict if c in df.columns})

    cols = ['data'] + list(rename_dict.values())

    if keep_price:
        cols = ['data', 'preco', 'retorno_log'] + list(rename_dict.values())

    return df[cols]

