# -----------------------------------------------------------
# Função Monte Carlo com σ constante
# -----------------------------------------------------------

def mc_sigma_constante(S0, K, T, sigma, r, q, n_sim=10000):
    """
    Simulador Monte Carlo (GBM risco-neutro) com σ constante.

    S0     : Preço inicial (PLD)
    K      : Strike
    T      : Tempo até o vencimento (anos)
    sigma  : Volatilidade anualizada (constante)
    r      : Taxa livre de risco
    q      : Yield/dividendo (0)
    n_sim  : Número de simulações MC
    """
    if sigma <= 0 or np.isnan(sigma):
        sigma = 1e-8  # evita problemas numéricos

    # Choques aleatórios
    Z = np.random.normal(0, 1, n_sim)

    # Simulação final
    ST = S0 * np.exp((r - q - 0.5*sigma**2)*T + sigma*np.sqrt(T)*Z)

    call = np.exp(-r*T) * np.mean(np.maximum(ST - K, 0))
    put  = np.exp(-r*T) * np.mean(np.maximum(K - ST, 0))

    return call, put

